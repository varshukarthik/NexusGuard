def _pan(rng: random.Random) -> str:
    L = "ABCDEFGHJKLMNPQRSTUVWXYZ"
    return "".join(rng.choice(L) for _ in range(3)) + "P" + rng.choice(L) + f"{rng.randint(1000, 9999)}" + rng.choice(L)


def seed(db: DBSession) -> None:
    if db.scalar(select(func.count(Company.id))):
        return
    log.info("Seeding NovaTech demo tenant…")
    rng = random.Random(14)
    now = datetime.now(timezone.utc)
    db.add_all([Company(id=NT, name="NovaTech Solutions", domain="novatech.demo"),
                Company(id=ORB, name="Orbit Labs", domain="orbitlabs.demo")])
    db.flush()

    deps = {n: Department(company_id=NT, name=n, code=c) for n, c in DEPARTMENTS}
    db.add_all(deps.values())
    db.add(Department(company_id=NT, name=GUEST_DEPARTMENT[0], code=GUEST_DEPARTMENT[1], is_public=False,
                      description="Pseudo-department used for Guest Mode sessions."))
    perms = {c: Permission(company_id=NT, code=c, description=d) for c, d in PERMISSIONS.items()}
    db.add_all(perms.values())
    db.flush()
    roles = {}
    for code, name, plist, desc in ROLES:
        r = Role(company_id=NT, code=code, name=name, description=desc)
        r.permissions = [perms[p] for p in dict.fromkeys(plist)]
        roles[code] = r
    db.add_all(roles.values())
    db.flush()

    pw = hash_password(DEMO_PASSWORD)
    users: dict[str, User] = {}
    for code, name, dept, role, title, clr, _, persona in USERS:
        first, last = name.lower().split()[0], name.lower().split()[-1]
        u = User(company_id=NT, employee_code=code, email=f"{first}.{last}@novatech.demo", full_name=name,
                 password_hash=pw, department_id=deps[dept].id, role_id=roles[role].id, job_title=title,
                 clearance=clr, location=rng.choice(["Hyderabad", "Hyderabad", "Bengaluru", "Pune"]),
                 phone=f"+91 9{rng.randint(100000000, 999999999)}", pan_number=_pan(rng),
                 bank_account=str(rng.randint(10 ** 11, 10 ** 12 - 1)),
                 joined_on=date(rng.randint(2014, 2025), rng.randint(1, 12), rng.randint(1, 28)), is_demo_persona=persona)
        users[code] = u
    db.add_all(users.values())
    db.flush()
    for code, *_rest in USERS:
        mgr = _rest[5]
        if mgr:
            users[code].manager_id = users[mgr].id

    # Tenant B
    odep = Department(company_id=ORB, name="People", code="PPL")
    operm = [Permission(company_id=ORB, code=c, description=d) for c, d in PERMISSIONS.items() if c in BASE]
    db.add(odep)
    db.add_all(operm)
    db.flush()
    orole = Role(company_id=ORB, code="employee", name="Employee", description="Orbit Labs employee")
    orole.permissions = operm
    db.add(orole)
    db.flush()
    db.add(User(company_id=ORB, employee_code="OL-0101", email="maya.collins@orbitlabs.demo", full_name="Maya Collins",
                password_hash=pw, department_id=odep.id, role_id=orole.id, job_title="People Partner",
                clearance="CONFIDENTIAL", is_demo_persona=True, location="Singapore"))
    db.flush()

    # Documents + vectors
    for spec in DOCUMENTS + CORE_DOCUMENTS + ORBIT_DOCUMENTS:
        (did, title, fn, dtype, dept, cls, adeps, aroles, fam, ver, eff, owner, content) = spec
        cid = NT if did.startswith("DOC") else ORB
        d = Document(id=did, company_id=cid, title=title, filename=fn, doc_type=dtype, department=dept,
                     classification=cls, allowed_departments=list(adeps), allowed_roles=list(aroles), family_key=fam,
                     version=ver, effective_date=date.fromisoformat(eff), status="published", content=content.strip(),
                     owner_id=users[owner].id if owner else None, summary=content.strip().split("\n")[0][:240],
                     created_at=datetime.fromisoformat(eff + "T09:00:00+05:30"),
                     updated_at=datetime.fromisoformat(eff + "T09:00:00+05:30"))
        db.add(d)
    db.flush()
    # Older versions are marked superseded (still readable for history, never preferred).
    fams: dict[str, list[Document]] = {}
    for d in db.scalars(select(Document)).all():
        fams.setdefault((d.company_id, d.family_key), []).append(d)
    for docs in fams.values():
        docs.sort(key=lambda x: x.effective_date)
        for d in docs[:-1]:
            d.status = "superseded"
    _seed_work(db, users, rng, now)
    _seed_history(db, users, rng, now)
    db.flush()

    # Large relational enterprise dataset (employees → departments → managers → projects → tasks → documents …)
    from .seed_large_dataset import generate
    generate(db, users, deps, rng=random.Random(2026), now=now)

    # Chunk + embed every document in batches (hybrid-search index is built lazily from these chunks).
    bulk_index(db, db.scalars(select(Document)).all())
    ensure_repositories(db)
    db.commit()
    log.info("Seed complete.")


