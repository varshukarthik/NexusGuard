def _seed_history(db, users, rng, now):
    by_code = users
    all_codes = [c for c in users]
    convs = []
    for code, title, q, a in CONVO_TEMPLATES:
        convs.append((code, title, q, a))
    while len(convs) < 56:
        code = rng.choice(all_codes)
        t, q, a = rng.choice(GENERIC_Q)
        convs.append((code, t, q, a))
    for i, (code, title, q, a) in enumerate(convs):
        ts = now - timedelta(days=rng.uniform(0.3, 12), minutes=i)
        c = Conversation(company_id=NT, user_id=by_code[code].id, title=title, created_at=ts, updated_at=ts)
        db.add(c)
        db.flush()
        db.add(Message(company_id=NT, conversation_id=c.id, role="user", content=q, created_at=ts))
        db.add(Message(company_id=NT, conversation_id=c.id, role="assistant", content=a, intent="information_retrieval",
                       meta={"engine": "offline", "seeded": True, "timeline": [], "sources": [], "actions": [],
                             "security": []}, created_at=ts + timedelta(seconds=3)))

    # ---- audit history (≈170 events) -------------------------------------------------------
    docs = {d.id: d for d in db.scalars(select(Document).where(Document.company_id == NT))}
