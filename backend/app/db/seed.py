def ensure_index(db: DBSession) -> None:
    """Re-embed if the embedding provider changed (e.g. an OpenAI key was added)."""
    stale = db.scalar(select(func.count(DocumentChunk.id)).where(DocumentChunk.embedding_model != embedder.model_id))
